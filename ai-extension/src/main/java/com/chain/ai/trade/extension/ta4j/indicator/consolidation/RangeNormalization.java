package com.chain.ai.trade.extension.ta4j.indicator.consolidation;

/**
 * 振幅归一化策略枚举。
 * <p>
 * 价值区间宽度（最高收盘价 - 最低收盘价）是一个绝对数值，
 * 需要除以一个“归一化分母”才能转换为相对百分比，以便跨品种、跨时间对比。
 * </p>
 */
public enum RangeNormalization {

    /**
     * 当前价格归一化（默认推荐）。
     * <p>
     * 公式：振幅 = (价值区间宽度 / 当前K线收盘价) × 100%
     * </p>
     * <p>
     * <b>优点：</b>振幅百分比直接映射账户盈亏，动态适应最新价格，最贴近实盘交易直觉。
     * </p>
     */
    CURRENT_PRICE,

    /**
     * 中价归一化。
     * <p>
     * 公式：振幅 = (价值区间宽度 / 价值区间中价) × 100%
     * </p>
     * <p>
     * <b>优点：</b>分母与箱体本身对称，统计学最稳健，不受最新K线收盘位置的影响。
     * </p>
     */
    MID_PRICE,

    /**
     * 绝对差值（不归一化）。
     * <p>
     * 振幅直接使用价值区间宽度，单位为价格点数（元/点）。
     * </p>
     * <p>
     * <b>适用场景：</b>单一固定品种（如国债期货）、价格中枢长期稳定时使用。
     * </p>
     */
    ABSOLUTE
}