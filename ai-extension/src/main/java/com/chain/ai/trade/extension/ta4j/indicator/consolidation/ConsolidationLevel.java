package com.chain.ai.trade.extension.ta4j.indicator.consolidation;

/**
 * 横盘强度等级枚举。
 * <p>
 * 基于价值区间振幅（按所选归一化策略计算）将横盘分为三个等级，
 * 不同等级对应不同的价格行为含义和交易策略。
 * </p>
 */
public enum ConsolidationLevel {

    /**
     * 超窄横盘（窒息）。
     * <p>
     * 振幅 ≤ 2%（默认阈值）。价格极度收敛，多空都在观望，
     * 流动性枯竭，大概率在 1~3 根 K 线内变盘。
     * </p>
     * <p>
     * <b>推荐策略：</b>挂突破单，等待放量方向。
     * </p>
     */
    ULTRA_TIGHT,

    /**
     * 标准窄幅横盘（蓄力）。
     * <p>
     * 2% < 振幅 ≤ 5%（默认阈值）。典型的中继整理形态，
     * 主力控盘良好，结构紧凑，方向未明但蓄势待发。
     * </p>
     * <p>
     * <b>推荐策略：</b>观察边界假突破，准备跟进趋势。
     * </p>
     */
    TIGHT,

    /**
     * 宽幅横盘（震荡）。
     * <p>
     * 5% < 振幅 ≤ 10%（默认阈值）。多空拉锯剧烈，
     * 高低点明确，但无明确趋势方向。
     * </p>
     * <p>
     * <b>推荐策略：</b>区间上下沿高抛低吸，不追涨杀跌。
     * </p>
     */
    WIDE,

    /**
     * 无效（非横盘）。
     * <p>
     * 振幅超过最大阈值（默认 10%），或数据不足无法判定。
     * 此时应放弃横盘识别，转入趋势跟踪策略。
     * </p>
     */
    INVALID
}